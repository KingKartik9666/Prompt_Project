//! Embed the Atlas content (content/sections.json and content/topics/*.json) into the wasm, so the
//! Atlas works offline with no file access. The same files are checked by `cargo test -p qcore`.

use std::{env, fs, path::PathBuf};

fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("content");
    println!("cargo:rerun-if-changed={}", root.display());
    let mut topics: Vec<PathBuf> = fs::read_dir(root.join("topics"))
        .map(|d| d.flatten().map(|e| e.path()).filter(|p| p.extension().is_some_and(|x| x == "json")).collect())
        .unwrap_or_default();
    topics.sort();
    let lit = |p: &PathBuf| format!("include_str!({:?})", p.display().to_string());
    let mut out = String::from("// generated by build.rs\n");
    out.push_str(&format!("pub const SECTIONS: &str = {};\n", lit(&root.join("sections.json"))));
    out.push_str("pub const TOPICS: &[&str] = &[\n");
    for p in &topics {
        println!("cargo:rerun-if-changed={}", p.display());
        out.push_str(&format!("    {},\n", lit(p)));
    }
    out.push_str("];\n");
    fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("content.rs"), out).unwrap();
}
